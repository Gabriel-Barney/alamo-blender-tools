"""On-demand ALO preflight. Never scan meshes from a draw handler."""
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
import math
import textwrap

import bpy
import bmesh
from bpy.props import BoolProperty, CollectionProperty, IntProperty, PointerProperty, StringProperty
from . import animation, quality, settings, utils

SHADOWS = {'MeshShadowVolume.fx', 'RSkinShadowVolume.fx'}


@dataclass
class Issue:
    severity: str
    code: str
    message: str
    fix: str
    obj: object = None
    material: object = None


def export_objects(context, include_hidden=True):
    objects = []
    def visit(collection):
        if collection.hide_viewport and not include_hidden:
            return
        objects.extend(obj for obj in collection.objects if obj.type == 'MESH'
                       and (include_hidden or obj.visible_get(view_layer=context.view_layer)))
        for child in collection.children:
            visit(child)
    visit(context.scene.collection)
    return list(dict.fromkeys(objects))


def _manifold(mesh):
    bm = bmesh.new()
    try:
        bm.from_mesh(mesh)
        return all(v.is_manifold for v in bm.verts) and all(len(e.link_faces) == 2 for e in bm.edges)
    finally:
        bm.free()


def _texture_found(reference, folder):
    image = bpy.data.images.get(reference)
    if image and image.source == 'FILE' and image.filepath:
        if Path(bpy.path.abspath(image.filepath, library=image.library)).is_file():
            return True
    paths = [Path(bpy.path.abspath(reference))]
    if folder:
        paths.append(Path(bpy.path.abspath(folder)) / Path(reference).name)
    if bpy.data.filepath:
        parent = Path(bpy.data.filepath).parent
        paths.extend(parent / sub / Path(reference).name for sub in ('', 'Textures', '../Textures'))
    return any(path.is_file() for path in paths)


def validate(context, full_quality=True, include_hidden=True, export_animations=True, texture_folder=''):
    """Return all detected issues without changing selection, mode or user data.

    Evaluation temporarily changes modifier/collection visibility, restored in
    finally blocks. Edit/Pose mode is deliberately not switched automatically.
    """
    issues = []
    def add(severity, code, message, fix, obj=None, material=None):
        issues.append(Issue(severity, code, message, fix, obj, material))
    if context.mode not in {'OBJECT', 'POSE'}:
        add('ERROR', 'MODE', 'Switch to Object Mode before validating/exporting.',
            'Finish the current edit or pose operation, then choose Object Mode.')
        return issues, 0
    objects = export_objects(context, include_hidden)
    armature = utils.findArmature()
    bones = {'Root'} | (set(armature.data.bones.keys()) if armature else set())
    if not objects:
        add('WARNING', 'EMPTY_SCOPE', 'No mesh objects in the export scope.',
            'Enable Export Hidden Objects or add a mesh. A skeleton-only ALO can still be exported.')
    if armature:
        if armature.hide_viewport or armature.hide_get():
            add('ERROR', 'HIDDEN_RIG', 'Active Skeleton is hidden.',
                'Reveal the skeleton in the Outliner before export.', armature)
        if any(abs(armature.matrix_basis[i][j] - (i == j)) > 1e-6 for i in range(4) for j in range(4)):
            add('WARNING', 'RIG_TRANSFORM', 'Active Skeleton has unapplied object transforms.',
                'Check its position, rotation and scale: ALO ignores object transforms.', armature)
        names = set()
        for bone in armature.data.bones:
            name = utils.clean_name(bone.name)
            if name in names or name == 'Root':
                add('ERROR' if name == 'Root' else 'WARNING', 'BONE_NAME', 'Duplicate or reserved exported bone name: ' + name,
                    'Rename the bone; Blender numeric suffixes are stripped and Root is generated by the exporter.', armature)
            names.add(name)
            if export_animations and (not name.isascii() or len(name.encode('utf8')) > 254):
                add('ERROR', 'BONE_ENCODING', 'Bone name cannot be written safely to ALA: ' + bone.name,
                    'Use an ASCII bone name of at most 254 characters, or disable Export Animations.', armature)
            if bone.EnableProxy:
                proxy = bone.ProxyName
                if not proxy:
                    add('WARNING', 'EMPTY_PROXY', 'Enabled proxy has no effect name: ' + bone.name,
                        'Set Proxy Name in the bone properties or disable Enable Proxy.', armature)
                elif len(proxy.encode('utf8')) > 254 or not proxy.isascii():
                    add('ERROR', 'PROXY_NAME', 'Proxy name exceeds this exporter\'s supported encoding/length: ' + bone.name,
                        'Use an ASCII proxy name of at most 254 characters.', armature)
    seen_materials = set()
    try:
        with quality.export_visibility(context):
            for obj in objects:
                start = len(issues)
                mesh = obj.data
                if not mesh.materials:
                    add('ERROR', 'MATERIAL', 'Missing material on object: ' + obj.name,
                        'Create a material and choose its ALAMO shader in Material Properties.', obj)
                elif any(mat is None for mat in mesh.materials):
                    add('ERROR', 'MATERIAL_SLOT', 'Unassigned material slot on object: ' + obj.name,
                        'Assign a material to each slot or remove empty slots.', obj)
                shaders = {mat.shaderList.shaderList for mat in mesh.materials if mat}
                shadow = bool(shaders & SHADOWS)
                if (shadow or obj.HasCollision) and len(mesh.materials) > 1:
                    add('ERROR', 'SPECIAL_MATERIALS', 'Multiple materials on shadow/collision mesh: ' + obj.name,
                        'Use one material on each shadow or collision object.', obj)
                if not shadow and not mesh.uv_layers:
                    add('ERROR', 'UV', 'Missing UV: ' + obj.name,
                        'Create and unwrap a UV map in the UV Editing workspace.', obj)
                if shadow and not _manifold(mesh):
                    add('ERROR', 'SHADOW_MANIFOLD', 'Non manifold geometry shadow mesh: ' + obj.name,
                        'In Edit Mode use Select > Select All by Trait > Non-Manifold; close holes and remove loose/internal faces.', obj)
                if any(abs(obj.matrix_basis[i][j] - (i == j)) > 1e-6 for i in range(4) for j in range(4)):
                    add('WARNING', 'TRANSFORM', 'Unapplied object transforms: ' + obj.name,
                        'ALO ignores object transforms. Apply intended transforms or use Create Constraint Bone for an attachment.', obj)
                rigs = [mod for mod in obj.modifiers if mod.type == 'ARMATURE']
                if any(shader.startswith('RSkin') for shader in shaders) and not rigs:
                    add('ERROR', 'SKIN_RIG', 'Skinned shader has no Armature modifier: ' + obj.name,
                        'Add an Armature modifier targeting the Active Skeleton and assign rigid vertex weights.', obj)
                for modifier in rigs:
                    if modifier.object is None or modifier.object != armature:
                        add('ERROR', 'RIG', 'Armature modifier does not match the Active Skeleton: ' + obj.name,
                            'Choose the same armature in the modifier and ALAMO Active Skeleton selector.', obj)
                for constraint in obj.constraints:
                    if constraint.type == 'CHILD_OF':
                        if not armature or constraint.target != armature or constraint.subtarget not in armature.data.bones:
                            add('ERROR', 'ATTACHMENT', 'Invalid Child Of bone attachment: ' + obj.name,
                                'Set the constraint target to the Active Skeleton and select an existing bone.', obj)
                    else:
                        add('WARNING', 'CONSTRAINT', 'Object constraint is not baked into the ALO: ' + constraint.name,
                            'Apply the intended result to geometry or attach the object to a bone.', obj)
                if any(i.severity == 'ERROR' for i in issues[start:]):
                    continue
                try:
                    with quality.evaluated_export_mesh(context, obj, full_quality) as evaluated:
                        _check_evaluated(evaluated, obj, bones, bool(rigs), full_quality, add)
                        used_slots = sorted({poly.material_index for poly in evaluated.polygons})
                        for index in used_slots:
                            material = evaluated.materials[index] if index < len(evaluated.materials) else None
                            if material is None or material.as_pointer() in seen_materials:
                                continue
                            seen_materials.add(material.as_pointer())
                            _check_material(material, obj, texture_folder, add)
                except Exception as exc:
                    add('ERROR', 'EVALUATION', 'Cannot evaluate ' + obj.name + ': ' + str(exc),
                        'Check modifiers and mesh data, then run validation again.', obj)
    except Exception as exc:
        add('ERROR', 'EVALUATION', 'Cannot prepare export evaluation: ' + str(exc),
            'Check scene/view-layer availability and run validation again.')
    if export_animations and armature:
        for action in bpy.data.actions:
            for slot in animation.matching_slots(action, armature):
                if any(curve.data_path.endswith('.scale') for curve in animation.action_curves(action, slot)):
                    add('WARNING', 'ANIMATED_SCALE', 'Animated scale is unsupported: ' + action.name,
                        'Remove scale animation or disable Export Animations. ALA writes translation, rotation and visibility only.', armature)
    rank = {'ERROR': 0, 'WARNING': 1, 'INFO': 2}
    return sorted(issues, key=lambda issue: rank[issue.severity]), len(objects)


def _check_evaluated(mesh, obj, bones, skinned, full_quality, add):
    def issue(severity, code, message, fix):
        add(severity, code, message + ': ' + obj.name, fix, obj)
    materials = [mesh.materials[p.material_index] if p.material_index < len(mesh.materials) else None for p in mesh.polygons]
    if any(mat is None for mat in materials):
        issue('ERROR', 'EVALUATED_MATERIAL', 'Unassigned material on evaluated mesh', 'Assign materials to faces created by modifiers.')
        return
    shadow = any(mat.shaderList.shaderList in SHADOWS for mat in materials)
    if not mesh.polygons:
        issue('WARNING', 'EMPTY_MESH', 'Evaluated mesh has no faces', 'Check render modifier visibility or add faces.')
    if not shadow and not mesh.uv_layers:
        issue('ERROR', 'EVALUATED_UV', 'Evaluated mesh has no UV map', 'Preserve a UV map through the modifier stack.')
    if not shadow and len(mesh.uv_layers) > 4:
        issue('ERROR', 'UV_LIMIT', 'More than four UV sets', 'Remove unused UV layers; ALO writes at most four.')
    if mesh.uv_layers and any(mat.shaderList.shaderList in settings.bumpMappingList for mat in materials):
        try:
            mesh.calc_tangents()
        except RuntimeError as exc:
            issue('ERROR', 'TANGENTS', 'Cannot calculate normal-map tangents (' + str(exc) + ')', 'Repair the active UV map and mesh topology.')
    if shadow and not _manifold(mesh):
        issue('ERROR', 'EVALUATED_SHADOW', 'Non manifold geometry after modifiers on shadow mesh', 'Fix or disable the modifier that opens or breaks the shadow volume.')
    if any(not math.isfinite(c) for vertex in mesh.vertices for c in vertex.co):
        issue('ERROR', 'NONFINITE', 'Non-finite vertex coordinates', 'Repair invalid geometry or modifier values.')
    if not shadow and any(not math.isfinite(c) for i in range(len(mesh.loops)) for c in quality.corner_normal(mesh, i)):
        issue('ERROR', 'NONFINITE_NORMAL', 'Non-finite normals', 'Recalculate normals or repair the imported shading attributes.')
    if any(not math.isfinite(c) for layer in mesh.uv_layers for uv in layer.data for c in uv.uv):
        issue('ERROR', 'NONFINITE_UV', 'Non-finite UV coordinates', 'Repair the UV map before exporting.')
    color = mesh.color_attributes.active_color
    if color and any(not math.isfinite(c) for entry in color.data for c in entry.color):
        issue('ERROR', 'NONFINITE_COLOR', 'Non-finite vertex colors', 'Repair the active color attribute.')
    # This is deliberately an upper bound, not a false 16-bit-limit blocker.
    if len(mesh.loops) > 65536:
        issue('INFO', 'PARTITION', 'Large mesh may use multiple ALO buffers', 'The exporter partitions buffers automatically after seam splitting, without reducing detail.')
    if skinned:
        missing = blended = unknown = 0
        for index in {i for poly in mesh.polygons for i in poly.vertices}:
            groups = [g for g in mesh.vertices[index].groups if g.weight > 0]
            if not groups:
                missing += 1
                continue
            if len(groups) > 1:
                blended += 1
            strongest = max(groups, key=lambda group: group.weight)
            if strongest.group >= len(obj.vertex_groups) or obj.vertex_groups[strongest.group].name not in bones:
                unknown += 1
        if missing:
            issue('ERROR', 'WEIGHTS_MISSING', f'Missing vertex group on object ({missing} evaluated vertices)', 'Assign every exported vertex to a bone group with positive weight.')
        if blended:
            issue('ERROR' if full_quality else 'WARNING', 'WEIGHTS_BLENDED', f'Exporter cannot preserve blended weights ({blended} evaluated vertices)', 'Use one bone group per vertex. Full Quality blocks weight loss; disabling it keeps only the strongest group.')
        if unknown:
            issue('ERROR', 'WEIGHTS_UNKNOWN', f'Vertex group does not match an exported bone ({unknown} evaluated vertices)', 'Rename/reassign the strongest-weight groups to bones in the Active Skeleton.')


def _check_material(material, obj, texture_folder, add):
    shader = material.shaderList.shaderList
    if shader == 'alDefault.fx':
        add('WARNING', 'DEFAULT_SHADER', 'Default ALAMO shader: ' + material.name,
            'Choose the intended game shader in Material Properties.', obj, material)
    for parameter in settings.material_parameter_dict.get(shader, ()):
        if not parameter:
            continue
        value = getattr(material, parameter)
        if isinstance(value, str):
            if len(value.encode('utf8')) > 254 or not value.isascii():
                add('ERROR', 'TEXTURE_NAME', 'Texture reference cannot be encoded: ' + material.name + ' / ' + parameter,
                    'Use an ASCII texture filename of at most 254 characters.', obj, material)
            elif not value or value == 'None':
                add('WARNING', 'TEXTURE_UNSET', 'Texture not assigned: ' + material.name + ' / ' + parameter,
                    'Assign a texture name if this shader input is used. Optional inputs may stay unset.', obj, material)
            elif not _texture_found(value, texture_folder):
                add('WARNING', 'TEXTURE_MISSING', 'Texture not found locally: ' + value,
                    'Set Texture Folder or load the image. ALO stores only its name; confirm the DDS exists in the game/mod Textures directory.', obj, material)
        else:
            values = tuple(value) if hasattr(value, '__len__') else (value,)
            if any(not math.isfinite(v) for v in values):
                add('ERROR', 'MATERIAL_VALUE', 'Non-finite shader value: ' + material.name + ' / ' + parameter,
                    'Replace NaN/infinite material values with finite numbers.', obj, material)


class ALAMO_PG_validation_issue(bpy.types.PropertyGroup):
    severity: StringProperty()
    code: StringProperty()
    message: StringProperty()
    fix: StringProperty()
    target: PointerProperty(type=bpy.types.Object)
    material: PointerProperty(type=bpy.types.Material)


class ALAMO_PG_validation(bpy.types.PropertyGroup):
    full_quality: BoolProperty(name='Full Quality', default=True)
    include_hidden: BoolProperty(name='Export Hidden Objects', default=True)
    export_animations: BoolProperty(name='Export Animations', default=True)
    texture_folder: StringProperty(name='Texture Folder', subtype='DIR_PATH', description='Optional directory for checking external texture filenames')
    issues: CollectionProperty(type=ALAMO_PG_validation_issue, options={'SKIP_SAVE'})
    active_issue: IntProperty(default=0)
    checked: StringProperty(options={'SKIP_SAVE'})
    mesh_count: IntProperty(options={'SKIP_SAVE'})
    checked_options: StringProperty(options={'SKIP_SAVE'})


def run(context, full_quality, include_hidden, export_animations):
    state = context.scene.alamo_validation
    state.full_quality, state.include_hidden, state.export_animations = full_quality, include_hidden, export_animations
    state.issues.clear()
    state.checked = ''
    issues, state.mesh_count = validate(context, full_quality, include_hidden, export_animations, state.texture_folder)
    for issue in issues:
        item = state.issues.add()
        item.severity, item.code, item.message, item.fix = issue.severity, issue.code, issue.message, issue.fix
        item.target, item.material = issue.obj, issue.material
    state.active_issue = 0
    state.checked = datetime.now().strftime('%H:%M:%S')
    state.checked_options = f'{full_quality}/{include_hidden}/{export_animations}/{state.texture_folder}'
    return issues


class ALAMO_OT_validate_export(bpy.types.Operator):
    """Check the evaluated export mesh and list errors, warnings and fixes"""
    bl_idname = 'alamo.validate_export'
    bl_label = 'Validate Model'
    use_export_options: BoolProperty(default=False, options={'HIDDEN'})
    full_quality: BoolProperty(default=True, options={'HIDDEN'})
    include_hidden: BoolProperty(default=True, options={'HIDDEN'})
    export_animations: BoolProperty(default=True, options={'HIDDEN'})

    def execute(self, context):
        options = self if self.use_export_options else context.scene.alamo_validation
        issues = run(context, options.full_quality, options.include_hidden, options.export_animations)
        errors = sum(i.severity == 'ERROR' for i in issues)
        warnings = sum(i.severity == 'WARNING' for i in issues)
        self.report({'WARNING'} if errors or warnings else {'INFO'}, f'Validation: {errors} errors, {warnings} warnings. See ALAMO > Export Validation.')
        return {'FINISHED'}


class ALAMO_OT_select_validation_issue(bpy.types.Operator):
    """Reveal and select the issue's object and material for editing"""
    bl_idname = 'alamo.select_validation_issue'
    bl_label = 'Select / Reveal Object'

    def execute(self, context):
        state = context.scene.alamo_validation
        if not 0 <= state.active_issue < len(state.issues):
            return {'CANCELLED'}
        issue = state.issues[state.active_issue]
        obj = issue.target
        if obj is None or context.scene.objects.get(obj.name) != obj:
            self.report({'WARNING'}, 'Object no longer exists in this scene; validate again.')
            return {'CANCELLED'}
        utils.setModeToObject()
        def reveal(layer):
            if obj.name in layer.collection.all_objects:
                if layer.exclude: layer.exclude = False
                layer.hide_viewport = False
                layer.collection.hide_viewport = False
                for child in layer.children: reveal(child)
        reveal(context.view_layer.layer_collection)
        context.view_layer.update()
        obj.hide_viewport = False
        obj.hide_set(False)
        obj.hide_select = False
        for selected in context.selected_objects: selected.select_set(False)
        obj.select_set(True)
        context.view_layer.objects.active = obj
        if issue.material:
            for index, slot in enumerate(obj.material_slots):
                if slot.material == issue.material:
                    obj.active_material_index = index
                    break
        return {'FINISHED'}


class ALAMO_UL_validation_issues(bpy.types.UIList):
    def draw_item(self, context, layout, data, item, icon, active_data, active_propname, index):
        layout.label(text=item.message, icon='ERROR' if item.severity == 'ERROR' else 'INFO')
        layout.label(text=item.severity.title())


def draw_results(layout, context, options=None, allow_select=True):
    state = context.scene.alamo_validation
    if not state.checked:
        layout.label(text='Run Validate Model to check the export.')
        return
    errors = sum(i.severity == 'ERROR' for i in state.issues)
    warnings = sum(i.severity == 'WARNING' for i in state.issues)
    layout.label(text=f'Last check: {errors} errors, {warnings} warnings', icon='ERROR' if errors or warnings else 'CHECKMARK')
    layout.label(text=f'{state.mesh_count} meshes checked at {state.checked}')
    layout.label(text='Run again after edits. Export always rechecks.')
    if options is None:
        options = (state.full_quality, state.include_hidden, state.export_animations)
    current_options = '/'.join(str(value) for value in options) + '/' + state.texture_folder
    if current_options != state.checked_options:
        layout.label(text='Options changed since last check.', icon='ERROR')
    if state.issues:
        layout.template_list('ALAMO_UL_validation_issues', '', state, 'issues', state, 'active_issue', rows=5)
        if 0 <= state.active_issue < len(state.issues):
            issue = state.issues[state.active_issue]
            box = layout.box()
            width = max(24, int(context.region.width / 7) - 5) if context.region else 42
            for line in textwrap.wrap(issue.message, width=width): box.label(text=line)
            box.label(text='How to fix:')
            for line in textwrap.wrap(issue.fix, width=width): box.label(text=line)
            if issue.target and allow_select:
                box.operator('alamo.select_validation_issue', icon='RESTRICT_SELECT_OFF')


class ALAMO_PT_export_validation(bpy.types.Panel):
    bl_label = 'Export Validation'
    bl_space_type = 'VIEW_3D'
    bl_region_type = 'UI'
    bl_category = 'ALAMO'
    bl_order = 1

    def draw(self, context):
        layout = self.layout
        state = context.scene.alamo_validation
        layout.prop(state, 'full_quality')
        layout.prop(state, 'include_hidden')
        layout.prop(state, 'export_animations')
        layout.prop(state, 'texture_folder')
        layout.operator('alamo.validate_export', icon='CHECKMARK')
        draw_results(layout, context)
        export = layout.operator('export.alo', text='Export ALO...', icon='EXPORT')
        export.fullQuality, export.exportHiddenObjects, export.exportAnimations = state.full_quality, state.include_hidden, state.export_animations


classes = (ALAMO_PG_validation_issue, ALAMO_PG_validation, ALAMO_OT_validate_export,
           ALAMO_OT_select_validation_issue, ALAMO_UL_validation_issues, ALAMO_PT_export_validation)
